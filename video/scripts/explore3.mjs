import { chromium } from '../../design/tools/node_modules/playwright-core/index.mjs';
const BASE = process.env.APP_URL ?? 'https://croplytics.xyz/';
const OUT = new URL('../raw/ex2/', import.meta.url).pathname;
const browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=metal', '--ignore-gpu-blocklist', '--hide-scrollbars'] });
const page = await browser.newPage({ viewport: { width: 1600, height: 900 }, deviceScaleFactor: 1 });
const idle = async (x = 800) => { await page.waitForFunction(() => { const m = window.__map; return m && m.loaded() && !m.isMoving() && m.areTilesLoaded(); }, null, { timeout: 90000, polling: 250 }).catch(() => {}); await page.waitForTimeout(x); };
await page.goto(BASE, { waitUntil: 'domcontentloaded' });
await page.waitForFunction(() => window.__map && window.__map.loaded() && document.querySelector('[data-testid="fields-panel"]'), null, { timeout: 120000 });
await idle(1500);
await page.click('[data-testid="row-car_colusa_rice"]');
await page.waitForFunction(() => window.__app?.ready, null, { timeout: 60000 }); await page.waitForTimeout(2500); await idle(1000);
await page.click('[data-testid="field-panel"] [data-testid="more-detail"]'); await page.waitForTimeout(1000);
const nt = page.locator('[data-testid="nation-toggle"]');
console.log('toggle count', await nt.count());
await nt.scrollIntoViewIfNeeded(); await page.waitForTimeout(500);
await page.screenshot({ path: OUT + 'c1.png' });
await nt.click(); await page.waitForTimeout(2500);
await page.screenshot({ path: OUT + 'c2.png' });
await page.locator('[data-testid="nt-drought"]').scrollIntoViewIfNeeded().catch(()=>{});
await page.waitForTimeout(800); await page.screenshot({ path: OUT + 'c3.png' });
console.log((await page.innerText('[data-testid="nation-tools"]')).replace(/\s+/g,' ').slice(0,1500));
await browser.close();
